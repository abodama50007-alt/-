export function selectSeededQuestions(
  mode: CompetitionMode,
  count: number
): CompetitionQuestion[] {
  const pool =
    mode === 'mixed'
      ? COMPETITION_QUESTIONS
      : COMPETITION_QUESTIONS.filter((q) => q.category === mode);
  const shuffled = [...pool];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled.slice(0, Math.min(count, shuffled.length));
}

export function getQuestionsByIds(ids: string[]): CompetitionQuestion[] {
  const map = new Map(COMPETITION_QUESTIONS.map((q) => [q.id, q]));
  return ids
    .map((id) => map.get(id))
    .filter((q): q is CompetitionQuestion => Boolean(q));
}
